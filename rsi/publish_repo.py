#!/usr/bin/env python3
"""Assemble the public GitHub repository in site/: code, aggregate results and a generated BENCHMARK.md.

Only whitelisted, aggregate files are copied. Never copied: observation-level data, site coordinates,
per-cell or per-site predictions (OOF arrays, neon_oof.csv, gate weights), raw downloads, global rasters.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "site"
A = ROOT / "artifacts"

CODE_DIRS = ["hicofuse", "oadsdm", "rsi", "scripts", "tests"]
RESULT_GLOBS = [
    "results/*.csv", "results/*.json",
    "hicofuse/cv_*.csv", "hicofuse/multires_*.csv", "hicofuse/results/coherence_audit.csv", "hicofuse/results/external_validation.csv",
    "oadsdm/*/summary.csv", "oadsdm/*/fold_metrics.csv", "oadsdm/*/paired_bootstrap.csv", "oadsdm/*/params.csv",
    "oadsdm/*/tuning.csv", "oadsdm/step1/*.csv",
    "rsi/it1/*.csv", "rsi/it2/metrics.csv", "rsi/it2/stack_weights.csv", "rsi/it3/*.csv", "rsi/it3/*.txt",
    "rsi/it4/*.csv", "rsi/it5_pool.csv", "rsi/it6/*.csv",
    "rsi/it7/*.csv", "rsi/it7/head_params.json", "rsi/it7_b20/*.csv", "rsi/it7_pool4/*.csv", "rsi/it7_pool4/head_params.json",
    "rsi/gbif_pool/tiles.json",
]
NEVER = ("neon_oof", "gate_weights", "site_features", "oof_", ".npz", ".npy", "dataset")


def copy_code():
    for d in CODE_DIRS:
        dst = SITE / d
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(ROOT / d, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "*.log"))
    docs = SITE / "docs"
    docs.mkdir(exist_ok=True)
    note = ("> Archived README of the foundation stage (single-species *Ae. albopictus* presence-background benchmark). "
            "Paths such as `..\\webapp` and `..\\.venv` refer to the original research workspace and its frozen cohort, "
            "which are not part of this public repository.\n\n")
    (docs / "FOUNDATION.md").write_text(note + (ROOT / "README.md").read_text(encoding="utf-8"), encoding="utf-8")


def copy_results():
    out = SITE / "artifacts"
    if out.exists():
        shutil.rmtree(out)
    n = 0
    for g in RESULT_GLOBS:
        for f in sorted(A.glob(g)):
            rel = f.relative_to(A)
            if any(x in str(rel) for x in NEVER) or "smoke" in str(rel):
                continue
            (out / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, out / rel)
            n += 1
    return n


# ------------------------------------------------------------------ BENCHMARK.md
def md(df: pd.DataFrame, k=3, index=True) -> str:
    d = df.reset_index() if index else df
    cols = [str(c) for c in d.columns]
    rows = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(cols))) + "|"]
    for _, r in d.iterrows():
        cells = []
        for v in r.values:
            if isinstance(v, (float, np.floating)):
                cells.append("–" if not np.isfinite(v) else f"{v:.{k}f}")
            else:
                cells.append(str(v))
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join(rows)


DES = ["random5", "block5", "block10", "block20", "loro", "env", "zone", "temporal", "spatiotemp"]
DL = {"random5": "Random", "block5": "Block 5°", "block10": "Block 10°", "block20": "Block 20°", "loro": "Leave region out",
      "env": "Env. cluster", "zone": "Climate zone", "temporal": "Temporal", "spatiotemp": "Space-time"}


def benchmark() -> str:
    S = []
    S.append("# Benchmark\n\nGenerated by `rsi/publish_repo.py` from the result files under `artifacts/`. "
             "Four model families were developed in sequence; each section states its task, labels and validation, "
             "because scores are **not comparable across sections** (different endpoints and cohorts).\n")

    # 1 foundation
    rc = pd.read_csv(A / "results/representation_comparison.csv")
    fm = pd.read_csv(A / "results/fusion_mlp_summary.csv").assign(endpoint="presence_background")
    fm = fm.rename(columns={"representation": "factor", "learner": "learner"})
    fm["learner"] = "MLP"
    t = pd.concat([rc, fm])
    t = t[t.endpoint == "presence_background"].pivot_table(index="factor", columns="learner", values="AP_mean")
    t = t.loc[[i for i in ("BioClim19", "Environment41", "AlphaEarth64", "Environment_AlphaEarth105", "Nonlinear_late_fusion") if i in t.index]]
    t.index.name = "Representation"
    S.append("## 1. Foundation: representation and fusion benchmark (*Ae. albopictus*)\n\n"
             "Task: presence vs. target-group background, 1,601 locations, 6 frozen spatial outer folds. Metric: average precision (AP). "
             "Code: `scripts/build_foundation_bundle.py`, `scripts/run_fusion_benchmark.py`.\n\n" + md(t) +
             "\n\nAlphaEarth64 alone matches environment + AlphaEarth early fusion; nonlinear late fusion does not help. "
             "Differences of ~0.01 AP are within fold spread.\n")

    # 2 OA-DSDM
    o = pd.read_csv(A / "oadsdm/Env41_AE64_tuned/summary.csv").set_index("model")
    o = o[["PB_AP", "AT_AUC", "NEON_OOF_AUC", "NEON_OOF_AP"]].rename(columns={
        "PB_AP": "Presence-background AP", "AT_AUC": "Austria survey AUC", "NEON_OOF_AUC": "NEON 2026 AUC", "NEON_OOF_AP": "NEON 2026 AP"})
    o.index.name = "Model"
    q = pd.read_csv(A / "oadsdm/step1/q1_effort_recoverability.csv")
    S.append("## 2. Observation-aware integrated SDM (OA-DSDM)\n\n"
             "Task: shared latent suitability with separate observation processes for opportunistic reports (with an effort-bias head) "
             "and repeat-visit surveys (occupancy-detection). Protocol frozen before fitting: `oadsdm/PROTOCOL.md`; identification argument: "
             "`oadsdm/THEORY.md`. Features Environment41 + AlphaEarth64, tuned L2. Code: `oadsdm/`, `scripts/run_oadsdm.py`, `scripts/semisynthetic.py`.\n\n"
             + md(o.sort_values("NEON 2026 AUC", ascending=False)) +
             "\n\nHuman-footprint (effort) covariates are largely recoverable from AlphaEarth "
             f"(spatial-CV R² up to {q['spatial_cv_R2'].max():.2f}), so presence-background models can learn reporting effort. "
             "Joint likelihoods change NEON transfer only slightly; the surveys available do not span the urban gradient where effort bias acts.\n")

    # 3 HiCo-Fuse
    c = pd.read_csv(A / "hicofuse/cv_summary.csv").set_index("model")
    ch = pd.read_csv(A / "hicofuse/cv_hier_summary.csv").set_index("model").add_suffix("")
    c.loc[["HiCo", "HiCoMoE"]] = ch.loc[["HiCo", "HiCoMoE"]].reindex(columns=c.columns).values
    c = c[["test_nll", "AUC_Ae_albopictus", "AUC_Ae_aegypti", "AUC_Culex", "AUC_Anopheles", "AUC_mean"]].sort_values("AUC_mean", ascending=False)
    c.columns = ["Log-loss", "AUC albopictus", "AUC aegypti", "AUC Culex", "AUC Anopheles", "Mean AUC"]
    c.index.name = "Architecture"
    ev = pd.read_csv(A / "hicofuse/results/external_validation.csv")
    ev["col"] = ev.dataset + " · " + ev.subset
    ev = ev.pivot_table(index="model", columns="col", values="AUC")
    ev = ev[[c for c in ("Kraemer Ae. albopictus · all", "Kraemer Ae. albopictus · >~110 km from iNat reports",
                         "Kraemer Ae. aegypti · all", "Kraemer Ae. aegypti · >~110 km from iNat reports", "NEON 2026 Ae. albopictus · 373 sites")
             if c in ev.columns]]
    ev.index.name = "Model"
    S.append("## 3. HiCo-Fuse: multi-species composition with global-to-local coherence\n\n"
             "Task: multinomial composition of iNaturalist Culicidae reports (Ae. albopictus, Ae. aegypti, Culex, Anopheles, other) "
             "per 0.05° cell, 7,004 report cells, 105 features (Climate 26, Landscape 11, Human 4, AlphaEarth 64). "
             "HiCo: η_s(x) = A_s(parent) + B_s(x) − log mean_{x'∈parent} exp B_s(x'), so every 0.5° parent equals the mean of its children exactly. "
             "Validation: 10° spatial blocks, 2 seeds. Code: `hicofuse/`.\n\n" + md(c) +
             "\n\nExternal checks (AUC, never used in training): Kraemer et al. (2015) compendium records and NEON 2026 trap detections. Two-part = composition × reporting-support model.\n\n" + md(ev) + "\n")

    # 4 RSI holdout matrix
    m1 = pd.read_csv(A / "rsi/it1/metrics.csv")
    order = ["RF", "HGB", "MLP+Coords", "MLP", "HiCo", "GatedMoE", "GLM", "kNN-geo", "Prior"]
    a1 = m1.groupby(["model", "design"])["AUC_mean"].mean().unstack()[DES].loc[order].rename(columns=DL)
    n1 = m1.groupby(["model", "design"])["nll"].mean().unstack()[DES].loc[order].rename(columns=DL)
    a1.index.name = n1.index.name = "Model"
    ps = pd.read_csv(A / "rsi/it1/prior_shift.csv")
    pl = ps[ps.design == "loro"].groupby(["model", "correction"])["nll"].mean().unstack()
    pl = pl.loc[[m for m in ("RF", "HGB", "MLP", "MLP+Coords", "HiCo", "GLM") if m in pl.index]]
    pl.index.name = "Model (leave region out, log-loss)"
    S.append("## 4. Spatial generalisation benchmark (research loop, iteration 1)\n\n"
             "Same composition task as section 3. Nine models under nine holdout designs (41 splits). "
             "Code: `rsi/common.py` (designs, metrics, models), `rsi/it1_baselines.py`.\n\n"
             "**Mean per-class AUC**\n\n" + md(a1) + "\n\n**Record-weighted multinomial log-loss** (lower is better)\n\n" + md(n1) +
             "\n\n**Transfer loss is class-prior shift.** Re-weighting the same predictions to the true held-out class frequencies "
             "(oracle) versus an unsupervised EM estimate (`rsi/it1b_prior_shift.py`):\n\n" + md(pl) + "\n")

    # 5 fusion / weighting / invariance / decay / pool / coherence
    m2 = pd.read_csv(A / "rsi/it2/metrics.csv")
    w2 = m2.groupby(["strategy", "design"])["AUC_mean"].mean().unstack()
    w2 = w2[[d for d in ("block10", "loro", "env") if d in w2.columns]].rename(columns=DL).sort_values(DL["loro"], ascending=False)
    w2.index.name = "Weighting (log-linear pool of experts)"
    inv = pd.read_csv(A / "rsi/it3/invariance.csv").groupby(["variant", "design"])["AUC_mean"].mean().unstack().rename(columns=DL)
    inv.index.name = "Objective / feature set"
    m4 = pd.read_csv(A / "rsi/it4/metrics.csv").groupby(["strategy", "design"])["AUC_mean"].mean().unstack().rename(columns=DL)
    m4 = m4.sort_values(DL["loro"], ascending=False)
    m4.index.name = "Fusion"
    m5 = pd.read_csv(A / "rsi/it5_pool.csv").groupby(["model", "features", "design"])["AUC_mean"].mean().unstack().rename(columns=DL)
    m5.index = [f"{a} · {b}" for a, b in m5.index]
    m5.index.name = "Model · features"
    m6 = pd.read_csv(A / "rsi/it6/metrics.csv")
    f6 = m6[m6.level == "fine"].groupby(["model", "design"])["AUC_mean"].mean().unstack().rename(columns=DL)
    f6.index.name = "Coherence arm (fine level)"
    coh = pd.read_csv(A / "rsi/it6/coherence.csv")
    flip = coh[coh.model.str.startswith("RF")]["dominant_flip"]
    S.append("## 5. Fusion, weighting and spatial-model experiments (iterations 2–6)\n\n"
             "All on the composition task with the holdout designs of section 4; mean per-class AUC.\n\n"
             "**Iteration 2 · weighting strategies** (`rsi/it2_weighting.py`)\n\n" + md(w2) +
             "\n\n**Iteration 3 · invariance objectives and causal feature subsets** (`rsi/it3_causal.py`)\n\n" + md(inv) +
             "\n\n**Iteration 4 · support-decay fusion with regime-matched training** (`rsi/it4_support_fusion.py`)\n\n" + md(m4) +
             "\n\n**Iteration 5 · exogenous species-pool covariates** (`rsi/it5_species_pool.py`)\n\n" + md(m5) +
             "\n\n**Iteration 6 · coherence versus accuracy** (`rsi/it6_coherence.py`). Separately fitted coarse and fine maps flip the dominant "
             f"class in {flip.min() * 100:.0f}–{flip.max() * 100:.0f}% of 0.5° parents; all other arms are coherent by construction.\n\n" + md(f6) + "\n")

    m7 = pd.read_csv(A / "rsi/it7/metrics.csv")
    m7b = pd.read_csv(A / "rsi/it7_pool4/metrics.csv")
    m7b = m7b[m7b.model.isin(["HF2", "HF2-shrink2"])].assign(model=lambda d: d.model + "+pool4")
    f7 = pd.concat([m7, m7b])
    f7 = f7[f7.level == "fine"]
    arms7 = ["RF", "HF2", "HF2-shrink2", "HF2+pool4", "HF2-shrink2+pool4"]
    a7 = f7.groupby(["model", "design"])["AUC_mean"].mean().unstack().loc[arms7].rename(columns=DL)
    n7 = f7.groupby(["model", "design"])["nll"].mean().unstack().loc[arms7].rename(columns=DL)
    a7.index.name = n7.index.name = "Arm (fine level)"
    S.append("## 6. HiCo-Fuse 2 (iteration 7)\n\n"
             "The rebuilt model: the HiCo coherence rule over a random-forest local term B, with a small region term "
             "A_s(P) = α_s + γ_s M_s(P) + w_s·z(P), where M is the forest's own parent map and z an exogenous species-pool layer "
             "(Kraemer compendium density; `+pool4` adds GBIF Culicidae 1900–2021 genus counts per 5° tile, `rsi/fetch_gbif_pool.py`). "
             "The head is fitted on 5°-block out-of-fold forest output with a ridge penalty towards the plain forest. `shrink2` pulls the head "
             "back to the forest in parents that are novel in environment or pool space (rule fixed before testing). "
             "Code: `rsi/it7_hicofuse2.py`; global maps `rsi/hf2_global.py`.\n\n**Mean per-class AUC**\n\n" + md(a7) +
             "\n\n**Log-loss** (lower is better)\n\n" + md(n7) +
             "\n\nHF2+pool4 beats the forest in 14/20 splits on both AUC and log-loss (sign test p = 0.12 each); "
             "log-loss with a whole world region held out remains slightly above the forest's. "
             "Kraemer-based external checks are not independent for HiCo-Fuse 2 because its pool layer uses the compendium.\n")

    S.append("## Reading the benchmark\n\n"
             "- Random-split skill is mostly interpolation; report leave-region-out and climate-zone results.\n"
             "- The random forest is the model to beat on every holdout design.\n"
             "- Most transfer error is the regional species mix (class prior), not the habitat relation.\n"
             "- HiCo's coherence rule can be applied to any model after training at no measurable accuracy cost.\n"
             "- HiCo-Fuse 2 (coherent forest + exogenous species pool + novelty trust) matches or beats the forest on ranking in every design.\n\n"
             "Full reasoning, hypotheses and failures: `rsi/memory/RESEARCH_MEMORY.md`.\n")
    return "\n".join(S)


def main():
    copy_code()
    n = copy_results()
    (SITE / "BENCHMARK.md").write_text(benchmark(), encoding="utf-8")
    print("results copied:", n)


if __name__ == "__main__":
    main()
